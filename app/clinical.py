def red_flags_in(text: str) -> list[str]:
    t = " " + " ".join(text.lower().replace("’", "'").split()) + " "
    found = []
    for words, msg in RED_FLAGS:
        if all(w in t for w in words) and msg not in found:
            # avoid "fit" inside other words ("benefit", "fitness")
            if words == ("fit",) and not any(f" {w} " in t or f" {w}s " in t or f" {w}," in t for w in ("fit",)):
                continue
            found.append(msg)
    return found
